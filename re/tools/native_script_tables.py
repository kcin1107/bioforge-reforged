"""Generate native/Sources/BioForgeCore/ScriptTokens.swift: the script keyword/function token tables (opcode names).

The tables were extracted from BIOFORGE.EXE's data segment with Ghidra (re/out/script_tokens.txt); they are engine opcode
names, not game art, so the native package embeds them as Swift source instead of re-running the Ghidra extraction.
Rerun after the table file changes:  re/.venv/bin/python -I re/tools/native_script_tables.py
"""
import os
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 're', 'out', 'script_tokens.txt')
OUT = os.path.join(ROOT, 'native', 'Sources', 'BioForgeCore', 'ScriptTokens.swift')

def tokbyte(s): return int(s, 16) if s.startswith('0x') and len(s) > 1 else ord(s)

def main():
    sec, tables = None, {'STATEMENTS': [], 'FUNCTIONS': []}
    for ln in open(SRC, encoding='latin1').read().split('\n'):
        if ln.startswith('['): sec = ln[1:].split()[0].split('@')[0]; continue
        p = ln.split('\t', 1)
        if len(p) == 2 and p[0] and p[1] and sec in tables: tables[sec].append((tokbyte(p[0]), p[1]))
    def rows(items): return '\n'.join('        (0x%02x, "%s"),' % x for x in items)
    src = f'''// Script token tables (generated by re/tools/native_script_tables.py from re/out/script_tokens.txt; do not edit).
// Engine opcode names extracted from BIOFORGE.EXE (DGROUP): statement keyword bytes and `@` function ids.
enum ScriptTokens {{
    /// Statement keyword token byte -> keyword (file order).
    static let statements: [(byte: Int, name: String)] = [
{rows(tables['STATEMENTS'])}
    ]
    /// `@` function id -> function name (file order).
    static let functions: [(id: Int, name: String)] = [
{rows(tables['FUNCTIONS'])}
    ]
}}
'''
    open(OUT, 'w').write(src)
    print(f'{OUT}: {len(tables["STATEMENTS"])} statements, {len(tables["FUNCTIONS"])} functions')

main()
