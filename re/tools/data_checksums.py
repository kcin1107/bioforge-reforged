"""Generate native/Sources/BioForgeCore/KnownData.swift: size and MD5 of the first 5000 bytes (ScummVM's detection
convention) of every game file the native port needs, from a game folder known to be GOG 2.1.0.14 (English).

Required: BIOFORGE.EXE and every file in the data folders. Left out on purpose: INSTALL.OPT (INSTALL.EXE rewrites it and
the port falls back to defaults without it), RED.OPT, OPT/, KEYCODE?.DAT, README/BAT, INSTALL.EXE/MSG and AILXMI.DLL (the port never reads them).
Run:  re/.venv/bin/python -I re/tools/data_checksums.py <game folder>
"""
import hashlib, os, sys
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, 'native', 'Sources', 'BioForgeCore', 'KnownData.swift')
DIRS = ['BODY', 'DATA', 'INITGAME', 'ITEMS', 'MONITORS', 'MUSIC', 'ROOMS', 'SCRIPT', 'SHOW', 'SOUND']
TOP = ['BIOFORGE.EXE']
PREFIX = 5000

def table(folder):
    """[(PATH, size, md5 of the first 5000 bytes)] sorted by path; PATH is upper case and '/'-separated."""
    rows, found = [], {}
    for n in os.listdir(folder):
        if n.upper() in TOP: found[n.upper()] = os.path.join(folder, n)
        elif n.upper() in DIRS:
            for dp, _, files in os.walk(os.path.join(folder, n)):
                for f in files:
                    full = os.path.join(dp, f)
                    found[os.path.relpath(full, folder).replace(os.sep, '/').upper()] = full
    for p in sorted(found):
        with open(found[p], 'rb') as fh: head = fh.read(PREFIX)
        rows.append((p, os.path.getsize(found[p]), hashlib.md5(head).hexdigest()))
    return rows

def render(rows):
    body = '\n'.join('        (\"%s\", %d, \"%s\"),' % r for r in rows)
    return f'''// Known game files (generated by re/tools/data_checksums.py from the GOG release 2.1.0.14, English; do not edit).
// Path (upper case), size, and MD5 of the first 5000 bytes (ScummVM's detection convention). No game data, only fingerprints.
enum KnownData {{
    static let release = "GOG 2.1.0.14 (English)"
    static let files: [(path: String, size: Int, md5: String)] = [
{body}
    ]
}}
'''

def main():
    if len(sys.argv) != 2 or not os.path.isdir(sys.argv[1]):
        sys.exit('usage: data_checksums.py <game folder>')
    rows = table(sys.argv[1])
    with open(OUT, 'w') as f: f.write(render(rows))
    print('wrote %d files to %s' % (len(rows), OUT))

if __name__ == '__main__': main()
